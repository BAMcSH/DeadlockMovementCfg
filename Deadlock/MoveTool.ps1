# Pwsh console.log controller by Leif (youtube.com/@leifdeadlock)

$wshell = New-Object -ComObject wscript.shell;

$GameRoot = Get-Location
$Log  = Join-Path $GameRoot 'game\citadel\console.log'
$LastPos  = Join-Path $GameRoot 'game\citadel\cfg\lastpos.cfg'
$Out = Join-Path $GameRoot 'game\citadel\cfg'

$pat = 'setpos_exact ([\s0-9.-]*);'
$listgen = 'newlist ([\sA-Za-z0-9-]*)'
$spotdefine = 'newspot ([\sA-Za-z0-9-]*)'
$listset = 'setlist ([\sA-Za-z0-9-]*)'
$spotoverwrite = 'setspot ([\sA-Za-z0-9-]*)'

$currentlist = Join-Path $Out "LeifDefault.cfg"
$currentname = 'LeifDefault'
$currentspot = 0
$listspotflag = 0

$existing = (Get-Content -Path $Log | Measure-Object).Count

Get-Content -Path $Log -Wait | ForEach-Object {
	if ($existing -gt 0) {
		$existing--
	}

	if (-not $existing) {
		$n = [regex]::Match($_, "Source2Shutdown")
		if ($n.Success){
			break
		}
		
		$j = [regex]::Match($_, $listset)
		if ($j.Success) {
			$currentname = $j.Value.Remove(0,8)
			$currentlist = Join-Path $Out "$($currentname).cfg"
			echo "List set to $($currentlist)"
		}
		
		$k = [regex]::Match($_, $listgen)
		if ($k.Success) {
			$k = $k.Value.Remove(0,8)
			$currentname = $k
			$currentlist = Join-Path $Out "$($k).cfg"
			Set-Content $currentlist -Value "// 0"
			Add-Content $currentlist -Value "// Autogenerated by Leif's MoveTool.ps1 (youtube.com/@leifdeadlock). Use the following in console for cycle binds:"
			Add-Content $currentlist -Value "// Bind bind 5 leif_cyclef; bind 7 leif_current ;bind 6 leif_cycleb"
			Add-Content $currentlist -Value "Alias $($currentname) $($currentname)_1"
			
			$toolcfg = Get-Content (Join-Path $Out "movetool.cfg")
			$toolcfg += $toolcfg[$toolcfg.Count - 1].Insert($toolcfg[$toolcfg.Count - 1].Length - 1, "echoln $($currentname);")
			$toolcfg[$coolcfg.Count - 2] = "exec $($currentname)"
			Set-Content (Join-Path $Out "movetool.cfg") -Value $toolcfg
			
			$wshell.SendKeys("exec movetool~")
			
			echo "$($currentlist) Created"
		}
		
		$l = [regex]::Match($_, $spotdefine)
		if ($l.Success) {
			$l = $l.Value.Remove(0,8)
			
			$old = Get-Content $currentlist
			$currentspot = [int]$old[0].Split(' ')[1] + 1
			$old[0] = "// $($currentspot)"
			if ($currentspot -gt 1) {
				$old[6] = "Alias $($currentname)_1 ""Alias leif_cyclef $($currentname)_2; Alias leif_current $($currentname)_spot1; Alias leif_cycleb $($currentname)_$($currentspot); $($currentname)_spot1; $($currentname)_hint1"""
				$modspot = if ($currentspot - 2 -lt 1) {$currentspot} else {$currentspot - 2}
				$old[$old.Count - 1] = "Alias $($currentname)_$($currentspot-1) ""Alias leif_cyclef $($currentname)_$($currentspot); Alias leif_current $($currentname)_spot$($currentspot-1); Alias leif_cycleb $($currentname)_$($modspot); $($currentname)_spot$($currentspot-1); $($currentname)_hint$($currentspot-1)"""
			}
			Set-Content $currentlist $old
			
			Add-Content $currentlist -Value "Alias $($currentname)_hint$($currentspot) ""echoln $($l)"""
			$listspotflag = 1
			$wshell.SendKeys("getpos_exact~")
		}
		
		<# $l = [regex]::Match($_, $spotoverwrite)
		if ($l.Success) {
			$l = $l.Value.Remove(0,8)
			$spotnum = $l.Split(' ')[0]
			if ($spotnum -lte (Get-Content $currentlist -TotalCount 1)) {
				Add-Content $currentlist -Value "Alias $($currentname)_hint $($l)"
				$listspotflag = 1
				$wshell.SendKeys("getpos_exact~")
			}
		} #>
		
		$m = [regex]::Match($_, $pat)
		if ($m.Success) {
			$m = $m.Value.Remove(0,13)
			if ($listspotflag) {
				$listspotflag = 0
				Add-Content $currentlist -Value "Alias $($currentname)_spot$($currentspot) setpos $($m)"
				$modspot = if ($currentspot - 1 -lt 1) {$currentspot} else {$currentspot - 1}
				Add-Content $currentlist -Value "Alias $($currentname)_$($currentspot) ""Alias leif_cyclef $($currentname)_1; Alias leif_current $($currentname)_spot$($currentspot); Alias leif_cycleb $($currentname)_$($modspot); $($currentname)_spot$($currentspot); $($currentname)_hint$($currentspot)"""
				$wshell.SendKeys("exec $($currentname)~")
			} else {
				Set-Content -Path $LastPos -Value ('setpos ' + $m)
			}
		}
	}
}

